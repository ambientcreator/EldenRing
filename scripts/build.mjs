import { mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const modules = [
  'tokens', 'typography', 'base', 'background', 'components/servers',
  'components/channels', 'components/header', 'components/home', 'components/chat',
  'components/composer', 'components/members', 'components/profiles',
  'components/menus', 'components/settings', 'components/voice',
  'components/misc', 'effects', 'accessibility', 'compatibility',
];
const mimeTypes = {
  svg: 'image/svg+xml',
  webp: 'image/webp',
  woff2: 'font/woff2',
};
const header = `/**
 * @name Golden Ruins
 * @author Golden Ruins contributors
 * @version 0.2.0
 * @description Weathered gold and quiet, translucent panels over the Golden Ruins landscape.
 * @license MIT
 */

/* Generated by scripts/build.mjs. Set --gr-* in Custom CSS or QuickCSS. */
/* Wallpaper supplied by the user. See CREDITS.md for image rights. */
`;
const assetPattern = /url\("\.\.\/assets\/([\w.-]+)"\)/g;
const output = new URL('dist/GoldenRuins.theme.css', root);

async function bundle() {
  const files = await Promise.all(modules.map(name => readFile(new URL(`src/${name}.css`, root), 'utf8')));
  const css = files.map((file, index) => `/* ${modules[index]} */\n${file.trim()}`).join('\n\n');
  const assetNames = [...new Set([...css.matchAll(assetPattern)].map(([, name]) => name))];
  const assets = new Map(await Promise.all(assetNames.map(async name => {
    const type = mimeTypes[name.split('.').at(-1)];
    if (!type) throw new Error(`Unsupported theme asset: ${name}`);
    const bytes = await readFile(new URL(`assets/${name}`, root));
    return [name, `url("data:${type};base64,${bytes.toString('base64')}")`];
  })));
  const licenseFiles = ['LICENSE', 'assets/forum-OFL.txt', 'assets/literata-OFL.txt'];
  const licenses = await Promise.all(licenseFiles.map(async name => {
    const license = await readFile(new URL(name, root), 'utf8');
    return `/*\n${license.trim()}\n*/`;
  }));

  return `${header}\n${css.replace(assetPattern, (_, name) => assets.get(name))}\n\n${licenses.join('\n\n')}\n`;
}

const check = process.argv[2] === '--check';
if (process.argv.length > (check ? 3 : 2)) {
  throw new Error('Usage: node scripts/build.mjs [--check]');
}

const expected = await bundle();
if (check) {
  const actual = await readFile(output, 'utf8');
  if (actual !== expected) throw new Error('Theme bundle is out of date. Run node scripts/build.mjs.');
  console.log('Theme bundle matches the source.');
} else {
  await mkdir(new URL('dist/', root), { recursive: true });
  await writeFile(output, expected);
  console.log('Built dist/GoldenRuins.theme.css');
}
